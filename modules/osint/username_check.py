def _check(url: str, expect: int) -> dict:
    r = net.fetch(url, max_bytes=500, timeout=8)
    return {"status": r.status, "taken": r.status == expect}


def run() -> None:
    user = ui.ask("Pseudo à vérifier").strip()
    if not user:
        ui.err("Pseudo vide.")
        return

    steps = [(name, (lambda u=url, e=exp: _check(u.format(u=user), e))) for name, (url, exp) in SITES.items()]
    results = ui.run_steps(f"RECHERCHE • {user}", steps)

    rows, found = [], 0
    for (name, _), r in zip(steps, results):
        if not r["ok"]:
            rows.append((name, ui.verdict("mid", "injoignable")))
            continue
        if r["data"]["taken"]:
            found += 1
            rows.append((name, ui.verdict("bad", f"pris ({SITES[name][0].format(u=user)})")))
        else:
            rows.append((name, ui.verdict("good", "libre")))
    ui.data_table(f"{user} • {found}/{len(SITES)} trouvé(s)", ["Plateforme", "Résultat"], rows, [BONE, BONE])
    ui.offer_save(f"username_{user}", {n: SITES[n][0].format(u=user) for n, r in zip(SITES, results) if r["ok"] and r["data"]["taken"]})